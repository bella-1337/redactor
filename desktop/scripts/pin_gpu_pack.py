"""Pin the desktop app's GPU pack: the CuPy and CUDA wheels, by URL and SHA-256.

    uv run --no-project --python 3.12 desktop/scripts/pin_gpu_pack.py

The versions are presidio/gpu-requirements.in's, so the app and the compose
GPU image use the same ones. For each target with NVIDIA GPU support (Windows
and Linux x64) this picks each version's wheel for CPython 3.12 from PyPI and
writes desktop/runtime/gpu-pack.json. The installers bundle that file only; a
computer with an NVIDIA GPU downloads the wheels on the app's first start and
checks each against its SHA-256 (pii_review.gpu.GpuPack).
"""

from __future__ import annotations

import json
import re
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "presidio" / "gpu-requirements.in"
OUT = REPO / "desktop" / "runtime" / "gpu-pack.json"

# Target triple (as in build_runtime.py) -> wheel platform tag.
TARGETS = {
    "x86_64-unknown-linux-gnu": re.compile(r"manylinux[^-]*_x86_64"),
    "x86_64-pc-windows-msvc": re.compile(r"win_amd64"),
}
PYTHON_TAGS = ("cp312-cp312", "py3-none")


def pins() -> list[tuple[str, str]]:
    found = []
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            name, _, version = line.partition("==")
            found.append((name.strip(), version.strip()))
    return found


def wheel_for(name: str, version: str, target: str) -> dict[str, object]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as response:
        files = json.load(response)["urls"]
    platform = TARGETS[target]
    for item in files:
        filename = item["filename"]
        if not filename.endswith(".whl") or not any(tag in filename for tag in PYTHON_TAGS):
            continue
        if filename.endswith("-any.whl") or platform.search(filename):
            return {"name": filename, "url": item["url"], "sha256": item["digests"]["sha256"], "size": item["size"]}
    raise SystemExit(f"no {target} wheel for {name}=={version}")


def main() -> int:
    packages = pins()
    pack = {
        "_comment": "Generated by desktop/scripts/pin_gpu_pack.py from presidio/gpu-requirements.in. "
        "Downloaded by the app only on computers with an NVIDIA GPU.",
        "targets": {target: [wheel_for(name, version, target) for name, version in packages] for target in TARGETS},
    }
    OUT.write_text(json.dumps(pack, indent=2) + "\n", encoding="utf-8")
    for target, wheels in pack["targets"].items():
        total = sum(int(wheel["size"]) for wheel in wheels)
        print(f"{target}: {len(wheels)} wheels, {total / 1e6:.0f} MB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
